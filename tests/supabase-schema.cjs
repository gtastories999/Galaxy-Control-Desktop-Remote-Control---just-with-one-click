const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
(async () => {
  const db = new PGlite();
  try {
    // Auth claims are mocked only in this isolated PostgreSQL test, never in the production schema.
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,is_anonymous boolean);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
    const tech = '00000000-0000-4000-8000-000000000001', guest = '00000000-0000-4000-8000-000000000002';
    const stranger = '00000000-0000-4000-8000-000000000003', unverified = '00000000-0000-4000-8000-000000000004';
    const instance = '00000000-0000-4000-8000-000000000011';
    await db.query('insert into auth.users values ($1,$2,now(),false),($3,null,null,true),($4,$5,now(),false),($6,$7,null,false)', [tech,'tech@example.com',guest,stranger,'other@example.com',unverified,'pending@example.com']);
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/schema.sql'),'utf8'));
    const as = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']); await db.exec('set role authenticated'); };
    const rpc = async (action,data={}) => (await db.query('select public.gc_exchange($1,$2::jsonb) as value',[action,JSON.stringify(data)])).rows[0].value;
    const denied = async (action,data) => { await assert.rejects(()=>rpc(action,data)); };
    await as(guest);
    await denied('online',{instance_id:instance});
    await as(unverified);
    await denied('online',{instance_id:instance});
    await as(tech);
    assert.equal((await rpc('online',{instance_id:instance,email:'victim@example.com'})).status,'online');
    assert.ok((await rpc('online',{instance_id:stranger})).error, 'Only one online instance is allowed');
    await assert.rejects(()=>db.query('select * from galaxy_private.technicians'));
    await as(guest);
    assert.ok((await rpc('request',{email:'victim@example.com'})).error, 'Caller cannot change the registered email');
    const session = await rpc('request',{email:'TECH@example.com'});
    assert.equal(session.status,'pending');
    const sid=session.session_id;
    await denied('accept',{session_id:sid});
    await denied('signal',{session_id:sid,signal:{type:'offer',sdp:'v=0'}});
    await as(stranger);
    await denied('poll',{session_id:sid});
    await denied('stop',{session_id:sid});
    await as(tech);
    assert.equal((await rpc('poll',{instance_id:instance})).session_id,sid);
    await denied('accept',{session_id:sid,instance_id:stranger});
    await rpc('accept',{session_id:sid,instance_id:instance});
    const sdp='v=0\r\nm=application 9 UDP/DTLS/SCTP webrtc-datachannel\r\na=fingerprint:sha-256 00:11\r\n';
    await as(guest);
    await denied('signal',{session_id:sid,signal:{type:'answer',sdp}});
    await rpc('signal',{session_id:sid,signal:{type:'offer',sdp,extra:'not forwarded'}});
    await denied('signal',{session_id:sid,signal:{type:'offer',sdp}});
    await denied('signal',{session_id:sid,signal:{type:'input',kind:'key',key:65}});
    await denied('signal',{session_id:sid,signal:{type:'frame',data:'abc'}});
    await denied('signal',{session_id:sid,signal:{type:'candidate',candidate:{candidate:'candidate:1 1 udp 1 203.0.113.10 9000 typ relay',sdpMid:'0',sdpMLineIndex:0}}});
    await as(tech);
    const poll=await rpc('poll',{instance_id:instance,session_id:sid});
    assert.deepEqual(poll.events.map(event=>event.signal),[{type:'offer',sdp}]);
    assert.equal((await rpc('poll',{instance_id:instance,session_id:sid,after_id:poll.events[0].id})).events.length,0);
    await rpc('signal',{instance_id:instance,session_id:sid,signal:{type:'answer',sdp}});
    await rpc('signal',{instance_id:instance,session_id:sid,signal:{type:'candidate',candidate:{candidate:'candidate:1 1 udp 1 203.0.113.10 45000 typ srflx raddr 192.168.1.2 rport 50000',sdpMid:'0',sdpMLineIndex:0}}});
    await db.exec('reset role');
    const row=(await db.query('select email,host(ip) as ip,port from galaxy_private.technicians where user_id=$1',[tech])).rows[0];
    assert.deepEqual(row,{email:'tech@example.com',ip:'203.0.113.10',port:45000});
    await as(guest);
    const incoming=await rpc('poll',{session_id:sid});assert.equal(incoming.events.length,2);
    await rpc('stop',{session_id:sid});
    await as(tech);
    assert.equal((await rpc('poll',{instance_id:instance,session_id:sid})).status,'closed');
    await denied('signal',{instance_id:instance,session_id:sid,signal:{type:'answer',sdp}});
    // Stopping the online app must close even a request not yet assigned to its UI.
    await as(stranger);
    const abandoned=await rpc('request',{email:'tech@example.com'});
    await as(tech);await rpc('stop',{instance_id:instance});
    await as(stranger);assert.equal((await rpc('poll',{session_id:abandoned.session_id})).status,'closed');
    await as(tech);await rpc('online',{instance_id:instance});
    await as(stranger);const beforeTakeover=await rpc('request',{email:'tech@example.com'});
    await db.exec('reset role');await db.query("update galaxy_private.technicians set valid_until=now()-interval '1 second' where user_id=$1",[tech]);
    await as(tech);await rpc('online',{instance_id:stranger});
    await as(stranger);assert.equal((await rpc('poll',{session_id:beforeTakeover.session_id})).status,'closed');
    await as(guest);
    for(let i=0;i<8;i++) await rpc('request',{email:'offline@example.com'});
    assert.match((await rpc('request',{email:'offline@example.com'})).error,/Too many/);
    // Lease expiry prevents stale IP mappings and abandoned sessions from being used.
    await db.exec('reset role');await db.query("update galaxy_private.technicians set valid_until=now()-interval '1 second' where user_id=$1",[tech]);
    await as(stranger);assert.match((await rpc('request',{email:'tech@example.com'})).error,/offline/);
    await db.exec('reset role');await db.exec('set role anon');
    await assert.rejects(()=>db.query("select public.gc_exchange('poll','{}'::jsonb)"));
    await db.exec('reset role');
    const security=await db.query("select p.prosecdef from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname='gc_exchange'");
    assert.equal(security.rows[0].prosecdef,false);
    const tables=await db.query("select relrowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='galaxy_private' and c.relkind='r'");
    assert.equal(tables.rows.length,4);
    assert.ok(tables.rows.every(row=>row.relrowsecurity));
    console.log('PASS: PostgreSQL schema, verified email ownership, exact lookup, IP/port update, private tables, cross-user/instance denial, acceptance, SDP/ICE, no media relay, cursor, expiry and rate limits');
  }finally{await db.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
